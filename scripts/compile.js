/**
 * scripts/compile.js
 * Compiles Solidity contracts using solc and writes ABI + Bytecode artifacts to build/
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import solc from 'solc';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const rootDir = path.resolve(__dirname, '..');
const contractsDir = path.join(rootDir, 'contracts');
const buildDir = path.join(rootDir, 'build');

if (!fs.existsSync(buildDir)) {
  fs.mkdirSync(buildDir, { recursive: true });
}

console.log('Compiling Solidity contracts with solc 0.8.24...');

const sources = {
  'AMMMath.sol': { content: fs.readFileSync(path.join(contractsDir, 'AMMMath.sol'), 'utf8') },
  'IPyth.sol': { content: fs.readFileSync(path.join(contractsDir, 'IPyth.sol'), 'utf8') },
  'MockPythOracle.sol': { content: fs.readFileSync(path.join(contractsDir, 'MockPythOracle.sol'), 'utf8') },
  'MonadUpDownAMM.sol': { content: fs.readFileSync(path.join(contractsDir, 'MonadUpDownAMM.sol'), 'utf8') },
  // Test-only attacker contract used by test/security_regressions.test.js (SEC-03)
  'HostileKeeper.sol': { content: fs.readFileSync(path.join(contractsDir, 'test', 'HostileKeeper.sol'), 'utf8') }
};

const input = {
  language: 'Solidity',
  sources,
  settings: {
    viaIR: true,
    optimizer: {
      enabled: true,
      runs: 200
    },
    outputSelection: {
      '*': {
        '*': ['abi', 'evm.bytecode.object']
      }
    }
  }
};

const output = JSON.parse(solc.compile(JSON.stringify(input)));

let hasErrors = false;
if (output.errors) {
  for (const err of output.errors) {
    if (err.severity === 'error') {
      hasErrors = true;
      console.error(`\x1b[31m[ERROR]\x1b[0m ${err.formattedMessage}`);
    } else {
      console.warn(`\x1b[33m[WARNING]\x1b[0m ${err.formattedMessage}`);
    }
  }
}

if (hasErrors) {
  console.error('Compilation failed with errors.');
  process.exit(1);
}

for (const [fileName, fileObj] of Object.entries(output.contracts)) {
  for (const [contractName, contractObj] of Object.entries(fileObj)) {
    const baseName = `${fileName.replace('.sol', '')}_sol_${contractName}`;
    const abiPath = path.join(buildDir, `${baseName}.abi`);
    const binPath = path.join(buildDir, `${baseName}.bin`);

    const binData = contractObj.evm.bytecode.object.startsWith('0x') 
      ? contractObj.evm.bytecode.object 
      : `0x${contractObj.evm.bytecode.object}`;

    fs.writeFileSync(abiPath, JSON.stringify(contractObj.abi, null, 2));
    fs.writeFileSync(binPath, binData);

    console.log(`[OK] Generated ${baseName}.abi & .bin (${contractObj.evm.bytecode.object.length / 2} bytes)`);
  }
}

const contractsJsDir = path.join(rootDir, 'src', 'contracts');
if (!fs.existsSync(contractsJsDir)) {
  fs.mkdirSync(contractsJsDir, { recursive: true });
}

if (output.contracts['MonadUpDownAMM.sol']?.MonadUpDownAMM?.abi) {
  const ammAbiJs = `// Auto-generated by scripts/compile.js\nexport const AMM_ABI = ${JSON.stringify(output.contracts['MonadUpDownAMM.sol'].MonadUpDownAMM.abi, null, 2)};\nexport default AMM_ABI;\n`;
  fs.writeFileSync(path.join(contractsJsDir, 'AMMAbi.js'), ammAbiJs);
  console.log('[OK] Generated src/contracts/AMMAbi.js');
}

if (output.contracts['MockPythOracle.sol']?.MockPythOracle?.abi) {
  const pythAbiJs = `// Auto-generated by scripts/compile.js\nexport const MOCK_PYTH_ABI = ${JSON.stringify(output.contracts['MockPythOracle.sol'].MockPythOracle.abi, null, 2)};\nexport default MOCK_PYTH_ABI;\n`;
  fs.writeFileSync(path.join(contractsJsDir, 'MockPythAbi.js'), pythAbiJs);
  console.log('[OK] Generated src/contracts/MockPythAbi.js');
}

console.log('\nCompilation completed successfully!');
